import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const sandbox={};sandbox.globalThis=sandbox;
vm.runInNewContext(fs.readFileSync('city-mission-v32.js','utf8'),sandbox);
const {createCityMission,dispatch,objective}=sandbox.FishmanCityMission;
let s=createCityMission({requiredRescues:3,bombSeconds:30});
assert.equal(s.phase,'rescue');
assert.match(objective(s),/0\/3/);
s=dispatch(s,{type:'RESCUE',id:'civilian-1'});
assert.equal(s.rescued,1);
s=dispatch(s,{type:'RESCUE',id:'civilian-1'});
assert.equal(s.rescued,1,'duplicate rescue must not count twice');
for(const id of ['civilian-2','civilian-3'])s=dispatch(s,{type:'RESCUE',id});
assert.equal(s.phase,'defence');
s=dispatch(s,{type:'DISABLE_GENERATOR',id:'generator-1'});
s=dispatch(s,{type:'DISABLE_GENERATOR',id:'generator-1'});
assert.equal(s.generatorsDisabled,1,'duplicate generator must not count twice');
s=dispatch(s,{type:'DISABLE_GENERATOR',id:'generator-2'});
assert.equal(s.phase,'bomb');
s=dispatch(s,{type:'STABILIZE_BOMB',pufferFishPresent:false});
assert.equal(s.phase,'bomb','puffer fish required');
s=dispatch(s,{type:'TICK',dt:5});
assert.equal(s.bombSeconds,25);
s=dispatch(s,{type:'STABILIZE_BOMB',pufferFishPresent:true});
assert.equal(s.phase,'boss');
s=dispatch(s,{type:'BOSS_DEFEATED'});
assert.equal(s.phase,'complete');
assert.equal(dispatch(s,{type:'TICK',dt:20}),s,'complete state is terminal');
let failure=createCityMission({requiredRescues:1,bombSeconds:30});
failure=dispatch(failure,{type:'RESCUE',id:'civilian-1'});
failure=dispatch(failure,{type:'DISABLE_GENERATOR',id:'generator-1'});
failure=dispatch(failure,{type:'DISABLE_GENERATOR',id:'generator-2'});
failure=dispatch(failure,{type:'TICK',dt:30});
assert.equal(failure.failed,true);
const retry=dispatch(failure,{type:'RETRY'});
assert.equal(retry.phase,'rescue');
assert.equal(retry.bombSeconds,30);
console.log('PASS v32 city mission state machine, duplicates, timer, retry and completion');
